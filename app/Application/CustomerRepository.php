<?php

declare(strict_types=1);

namespace App\Application;

use App\Domain\Customer;
use DateTimeImmutable;

/**
 * Persists customers. Every read only sees active (non soft-deleted) rows, and a missing row is reported as
 * ApiException RESOURCE-NOT-FOUND-01.
 */
interface CustomerRepository
{
    public function get(string $id): Customer;

    /**
     * Reads the customer and takes a row lock that excludes every other lock on it. Deleting a customer uses it so
     * the "has orders?" check and the soft delete cannot interleave with an order creation.
     */
    public function lockForUpdate(string $id): Customer;

    /**
     * Reads the customer and takes a shared row lock: many orders can be created for one customer at once, but
     * none while that customer is being deleted (and vice versa).
     */
    public function lockForShare(string $id): Customer;

    /** Inserts the customer and gives it the id generated by the database. */
    public function create(Customer $customer): void;

    /** Writes the customer if its version still matches the row; otherwise CONFLICT-00. */
    public function update(Customer $customer): void;

    public function softDelete(string $id, string $actor, DateTimeImmutable $at): void;

    /** Both uniqueness checks ignore the customer $except (null to ignore none). */
    public function taxIdTaken(string $taxId, ?string $except): bool;

    public function passportTaken(string $passport, ?string $except): bool;

    /** @return Page<Customer> */
    public function search(SearchRequest $request): Page;
}
